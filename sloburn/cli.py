"""sloburn: generate SLO burn-rate alerts for Prometheus."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

from .dashboard import build_dashboard
from .generator import SLOSpec, budget_report, build_rules


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str):
    # Multi-line PromQL reads much better as a literal block.
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|" if "\n" in value else None)


_Dumper.add_representer(str, _str)


def dump_rules(rules: dict, source: str) -> str:
    header = f"# Generated by sloburn from {source}. Do not edit by hand; regenerate instead.\n"
    return header + yaml.dump(rules, Dumper=_Dumper, sort_keys=False, width=1000)


def load_spec(path: str) -> SLOSpec:
    with open(path, encoding="utf-8") as f:
        return SLOSpec.from_dict(yaml.safe_load(f))


def _write(path: str | None, text: str) -> None:
    if path is None:
        sys.stdout.write(text)
        return
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {path}", file=sys.stderr)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="sloburn", description=__doc__)
    sub = parser.add_subparsers(dest="cmd", required=True)

    gen = sub.add_parser("generate", help="write Prometheus recording + alerting rules for an SLO spec")
    gen.add_argument("spec", help="SLO spec YAML file")
    gen.add_argument("-o", "--output", help="rules file to write (default: stdout)")
    gen.add_argument("--dashboard", metavar="FILE", help="also write a Grafana dashboard JSON")

    bud = sub.add_parser("budget", help="print the error budget and alert thresholds")
    bud.add_argument("spec", nargs="?", help="SLO spec YAML file (or use --objective/--window)")
    bud.add_argument("--objective", type=float, help="SLO objective in percent, e.g. 99.9")
    bud.add_argument("--window", help="SLO window, e.g. 30d")

    args = parser.parse_args(argv)
    try:
        if args.cmd == "generate":
            spec = load_spec(args.spec)
            _write(args.output, dump_rules(build_rules(spec), Path(args.spec).name))
            if args.dashboard:
                _write(args.dashboard, json.dumps(build_dashboard(spec), indent=2) + "\n")
        else:
            if args.spec:
                spec = load_spec(args.spec)
                objective, window = float(spec.objective), spec.window
            elif args.objective is not None and args.window:
                objective, window = args.objective, args.window
            else:
                parser.error("budget needs a spec file or both --objective and --window")
            print(budget_report(objective, window))
    except (OSError, ValueError, yaml.YAMLError) as e:
        print(f"sloburn: error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
